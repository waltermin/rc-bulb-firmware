"""Build + check the Lemtone module.

  python build.py test   host unit tests (test/test_lemtone.c) with the host C compiler
  python build.py web    wasm32 solver -> web/lemtone_tool.html (self-contained page),
                         then checks the wasm against test/lemtone_vectors.h under node
  python build.py        both

Host compiler: $CC if set, else cc/gcc/clang on PATH, else MSVC (found via vswhere-style
search; vcvars is not needed). WebAssembly: clang with the wasm32 target + wasm-ld
(stock LLVM), no emscripten and no libc: lemtone.c is freestanding.

The model (lemtone_model_default.c / lemtone_model.json) and the test vectors are
generated by calibration/export_lemtone_model.py and calibration/lemtone_ref.py.
"""
import base64
import glob
import json
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = [os.path.join(HERE, "lemtone.c"), os.path.join(HERE, "lemtone_model_default.c")]


def run(cmd, **kw):
    print("+", " ".join(cmd))
    subprocess.run(cmd, check=True, **kw)


def find_msvc():
    roots = glob.glob(r"C:\Program Files\Microsoft Visual Studio\*\*\VC\Tools\MSVC\*") + \
        glob.glob(r"C:\Program Files (x86)\Microsoft Visual Studio\*\*\VC\Tools\MSVC\*")
    kits = sorted(glob.glob(r"C:\Program Files (x86)\Windows Kits\10\Include\10.*"))
    if os.name != "nt" or not roots or not kits:
        return None
    msvc, ver = sorted(roots)[-1], os.path.basename(kits[-1])
    inc = rf"C:\Program Files (x86)\Windows Kits\10\Include\{ver}"
    lib = rf"C:\Program Files (x86)\Windows Kits\10\Lib\{ver}"
    env = dict(os.environ)
    env["INCLUDE"] = ";".join([rf"{msvc}\include", rf"{inc}\ucrt", rf"{inc}\um", rf"{inc}\shared"])
    env["LIB"] = ";".join([rf"{msvc}\lib\x64", rf"{lib}\ucrt\x64", rf"{lib}\um\x64"])
    env["PATH"] = rf"{msvc}\bin\Hostx64\x64;" + env["PATH"]
    return env, rf"{msvc}\bin\Hostx64\x64\cl.exe"


def test():
    out = tempfile.mkdtemp(prefix="lemtone_test_")
    exe = os.path.join(out, "test_lemtone.exe" if os.name == "nt" else "test_lemtone")
    srcs = [os.path.join(HERE, "test", "test_lemtone.c")] + SRC
    inc = [HERE, os.path.join(HERE, "test")]
    cc = os.environ.get("CC") or next((c for c in ("cc", "gcc") if shutil.which(c)), None)
    if cc:
        run([cc, "-std=c11", "-O2", "-Wall", "-Wextra", *[f"-I{d}" for d in inc], *srcs, "-lm", "-o", exe])
    else:
        found = find_msvc()
        if not found:
            sys.exit("no host C compiler found (set CC)")
        env, cl = found
        run([cl, "/nologo", "/W4", "/O2", "/std:c11", *[f"/I{d}" for d in inc], *srcs,
             f"/Fo{out}\\", f"/Fe{exe}"], env=env, stdout=subprocess.DEVNULL)
    run([exe])


def clang():
    for c in (os.environ.get("WASM_CLANG"), shutil.which("clang"), r"C:\Program Files\LLVM\bin\clang.exe"):
        if c and os.path.exists(c):
            return c
    sys.exit("clang with the wasm32 target not found (set WASM_CLANG)")


def web():
    wasm = os.path.join(tempfile.mkdtemp(prefix="lemtone_wasm_"), "lemtone.wasm")
    run([clang(), "--target=wasm32", "-std=c11", "-O2", "-ffreestanding", "-fno-builtin", "-nostdlib",
         "-Wall", "-Wextra", f"-I{HERE}", "-Wl,--no-entry", "-Wl,--strip-all",
         os.path.join(HERE, "web", "lemtone_wasm.c"), *SRC, "-o", wasm])
    blob = open(wasm, "rb").read()
    web_dir = os.path.join(HERE, "web")
    tpl = open(os.path.join(web_dir, "lemtone_tool.template.html"), encoding="utf-8").read()
    model = json.load(open(os.path.join(HERE, "lemtone_model.json"), encoding="utf-8"))
    if "spd" not in model:
        sys.exit("lemtone_model.json has no spectra: re-run calibration/export_lemtone_model.py")
    spd = {"wl": model["spd_wl"], "knots": model["knots"], "spd": model["spd"]}
    inline = {
        '/*WASM_B64*/""': '"' + base64.b64encode(blob).decode() + '"',
        "/*CRI_TABLES*/null": open(os.path.join(web_dir, "cri_tables.json"), encoding="utf-8").read().strip(),
        "/*MODEL_SPD*/null": json.dumps(spd, separators=(",", ":")),
        "/*CRI_JS*/": open(os.path.join(web_dir, "cri.js"), encoding="utf-8").read(),
    }
    html = tpl
    for marker, text in inline.items():
        assert html.count(marker) == 1, f"template must contain {marker} exactly once"
        html = html.replace(marker, text)
    html = html.replace("<!-- lemtone_tool.template.html — source of lemtone_tool.html.",
                        "<!-- GENERATED by build.py from lemtone_tool.template.html; do not edit.", 1)
    dst = os.path.join(HERE, "web", "lemtone_tool.html")
    open(dst, "w", encoding="utf-8", newline="\n").write(html)
    print(f"wrote {dst} ({len(blob)} B wasm)")
    if shutil.which("node"):
        run(["node", os.path.join(web_dir, "check_wasm.mjs"), wasm,
             os.path.join(HERE, "test", "lemtone_vectors.h")])
        cases = os.path.join(HERE, "test", "cri_cases.json")
        if os.path.exists(cases):
            run(["node", os.path.join(web_dir, "check_cri.mjs"), os.path.join(web_dir, "cri_tables.json"), cases])
    else:
        print("node not found: skipped the wasm and CRI checks")


if __name__ == "__main__":
    what = sys.argv[1] if len(sys.argv) > 1 else "all"
    if what in ("test", "all"):
        test()
    if what in ("web", "all"):
        web()
