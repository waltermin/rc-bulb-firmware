typedef struct {
    const char *name;
    float a, b, lm, f;
} preset_t;

// OKLab chromaticities from the tool page's presets
static const preset_t PRESETS[] = {
    {"2700K 480 lm", 0.0744f, 0.1536f, 480.0f, 1.0f},  {"4000K 600 lm", 0.0328f, 0.0800f, 600.0f, 1.0f},
    {"6500K 600 lm", 0.0088f, -0.0056f, 600.0f, 1.0f}, {"rated 1000 lm (clamps)", 0.0448f, 0.0608f, 1000.0f, 1.0f},
    {"red 30 lm", 0.4616f, 0.2192f, 30.0f, 0.0f},      {"amber 180 lm", 0.1464f, 0.2256f, 180.0f, 0.5f},
    {"green 72 lm", -0.5176f, 0.2040f, 72.0f, 0.0f},   {"blue 15 lm", 0.0584f, -0.9408f, 15.0f, 0.0f},
    {"pink 90 lm", 0.2048f, -0.0304f, 90.0f, 0.5f},    {"candle 6 lm", 0.1432f, 0.2032f, 6.0f, 1.0f},
    {"red night light 0.5 lm", 0.4616f, 0.2192f, 0.5f, 0.0f}, {"imaginary violet 20 lm", 0.79f, -1.12f, 20.0f, 0.5f},
};

static void fade(const char *name, float a, float b, float f, float lm_hi, float lm_lo, int steps, int step_ms) {
    printf("ST fade %s: %d -> %d mlm -> back, %d steps each way @ %d ms\n", name, (int)(lm_hi * 1000),
           (int)(lm_lo * 1000), steps, step_ms);
    for (int k = 0; k <= 2 * steps; k++) {
        const float t = k <= steps ? (float)k / steps : (float)(2 * steps - k) / steps;
        send(a, b, lm_hi * powf(lm_lo / lm_hi, t), f);
        vTaskDelay(pdMS_TO_TICKS(step_ms));
    }
}

static void test_visible(void) {
    printf("ST ---- 3. visible sequence ----\n");
    for (int k = 0; k < N_OF(PRESETS); k++) {
        const preset_t *p = &PRESETS[k];
        printf("ST show %s\n", p->name);
        send(p->a, p->b, p->lm, p->f);
        vTaskDelay(pdMS_TO_TICKS(2500));
    }
    // across the 180 / 60 lm period tiers and down to the long-period region
    fade("2700K F1", 0.0744f, 0.1536f, 1.0f, 400.0f, 0.2f, 120, 100);
    fade("red F0 (desat path)", 0.4616f, 0.2192f, 0.0f, 40.0f, 0.05f, 60, 100);
}

// ---- driver -----------------------------------------------------------------------

static void selftest_task(void *arg) {
    (void)arg;
    vTaskDelay(pdMS_TO_TICKS(3000));  // let boot logging settle
    s_id = bulb_config_get_u8(CFG_BULB_ID);
    printf("\nST ==== LEMTONE SELFTEST (bulb id %u, heap free %u B) ====\n", s_id, esp_get_free_heap_size());

    static lemtone_ctx_t ctx;
    lemtone_init(&ctx, &LEMTONE_MODEL_DEFAULT);
    printf("ST model %s, lm_per_y %d e-6\n", ctx.m->id, (int)(ctx.m->lm_per_y * 1e6f));

    test_vectors(&ctx);
    test_path();
    test_visible();

    const controller_lemtone_stats_t c = cstats();
    const sniffer_lt_stats_t s = sstats();
    printf("ST ---- summary ----\n");
    printf("ST controller: %u applies, solve max %u us, pwm publish max %u us, min free stack %u B, %u fallbacks\n",
           c.applies, c.max_solve_us, c.max_pwm_us, c.min_stack_free, c.fallbacks);
    printf("ST sniffer: %u posted, %u repeats dropped, %u lost to a full queue\n", s.posted, s.repeats, s.dropped);
    printf("ST heap free %u B, selftest task stack free %u B\n", esp_get_free_heap_size(),
           (unsigned)uxTaskGetStackHighWaterMark(NULL));
    check(s.dropped == 0, "no values lost to a full controller queue");
    check(c.min_stack_free >= 512, "controller stack margin >= 512 B");
    if (s_fails) printf("ST SELFTEST FAIL %d of %d\n", s_fails, s_checks);
    else printf("ST SELFTEST PASS (%d checks)\n", s_checks);
    printf("ST bulb falls back to its default in %u ms; normal operation continues\n",
           bulb_config_get_u32(CFG_FALLBACK_MS));
    vTaskDelete(NULL);
}

void selftest_start(void) {
    xTaskCreate(selftest_task, "selftest", 4096, NULL, 2, NULL);
}

